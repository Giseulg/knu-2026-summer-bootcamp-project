import { expect, test } from '@playwright/test'

test.use({ viewport: { width: 320, height: 568 } })

test('mobile village actions fit and the profile and exploration menus work', async ({ page }) => {
  await page.goto('/')
  await page.locator('#nick').fill('독자')
  await page.getByRole('button', { name: '소설', exact: true }).click()
  await page.getByRole('button', { name: '시작하기' }).click()
  const actions = page.locator('.quest-actions')
  await expect(actions).toBeVisible()
  expect(await actions.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path: test.info().outputPath('mobile-village.png') })
  await page.evaluate(() => document.querySelector('.appbar')?.setAttribute('data-test-persistent', 'yes'))
  await page.getByRole('link', { name: '문장 단서 찾기' }).click()
  await expect(page).toHaveURL(/\/library\/rain$/)
  await expect(page.locator('.appbar')).toHaveAttribute('data-test-persistent', 'yes')
  await expect(page.getByRole('navigation', { name: '주요 메뉴' })).toBeVisible()
  await expect(page.getByRole('link', { name: '서재', exact: true })).toHaveAttribute('aria-current', 'page')
  await expect(page.locator('.mr-text')).toBeVisible()
  await expect(page.locator('.mr-header')).toHaveCount(0)
  await page.getByRole('button', { name: '글자 움직이기' }).click()
  await expect(page.getByRole('button', { name: '움직임 멈추기' })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('mobile-reader.png') })

  await page.goto('/my/interests')
  await page.getByRole('checkbox', { name: '소설' }).uncheck()
  await page.getByRole('checkbox', { name: '전공 자료' }).check()
  await page.getByRole('button', { name: '관심 분야 저장' }).click()
  await expect(page.getByRole('status')).toHaveText('저장했어요.')
  await page.reload()
  await expect(page.getByRole('checkbox', { name: '전공 자료' })).toBeChecked()
  await page.screenshot({ path: test.info().outputPath('mobile-interests.png') })

  await page.getByRole('link', { name: '탐색', exact: true }).click()
  await page.getByRole('link', { name: /해시 버킷/ }).click()
  await page.getByRole('link', { name: '탐색 목록으로' }).click()
  await expect(page).toHaveURL(/\/explore$/)

  await page.goto('/my/data')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '내 데이터 내려받기' }).click()
  expect((await download).suggestedFilename()).toBe('reading-fun-data.json')
  await page.getByRole('button', { name: '데모 초기화' }).click()
  await page.getByRole('button', { name: '취소' }).click()
  await expect(page.getByRole('button', { name: '초기화 확인' })).toHaveCount(0)
})
